"""Draw the 挚阅 icon (月与书: a moon over a closed book) into every place
that ships it. The artwork is three flat shapes, so it is drawn from their
geometry here rather than resized from a picture.

Usage, from app/: python tool/make_app_icon.py
"""
import os
import struct
import zlib

import numpy as np

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEAL = '#1E3A3A'

# On a 1024 square: (kind, colour, geometry). Circle: cx, cy, r.
# Rounded rect: x, y, w, h, corner radius. Later shapes paint over earlier ones.
ART = [
    ('circle', '#F1E6D2', (512, 430, 170)),
    ('rect', '#C8613E', (262, 640, 500, 96, 14)),
    ('rect', '#E48A62', (262, 640, 500, 22, 11)),
]

# A tile sits this far in from the edge of its square, with corners rounded
# to this share of its side — the same frame the old Windows icon used.
INSET = 8 / 256
CORNER = 0.2237


def rgb(hex_colour):
    return np.array([int(hex_colour[i:i + 2], 16) for i in (1, 3, 5)], float)


def rounded_rect(px, py, x, y, w, h, r):
    """Signed distance to a rounded rectangle: negative inside."""
    qx = np.abs(px - (x + w / 2)) - (w / 2 - r)
    qy = np.abs(py - (y + h / 2)) - (h / 2 - r)
    outside = np.hypot(np.maximum(qx, 0), np.maximum(qy, 0))
    return outside + np.minimum(np.maximum(qx, qy), 0) - r


def distance(kind, g, px, py):
    if kind == 'circle':
        cx, cy, r = g
        return np.hypot(px - cx, py - cy) - r
    return rounded_rect(px, py, *g)


def tile(size):
    """The icon as a rounded teal tile on a transparent square, RGBA bytes."""
    centres = np.arange(size) + 0.5
    px, py = np.meshgrid(centres, centres)
    side = size * (1 - 2 * INSET)
    edge = size * INSET
    colour = np.zeros((size, size, 3))
    alpha = np.zeros((size, size))

    def paint(d, c, scale):
        # Edge coverage from the distance to the shape, in pixels.
        a = np.clip(0.5 - d / scale, 0, 1)
        colour[:] = colour * (1 - a[..., None]) + rgb(c) * a[..., None]
        return a

    a = paint(rounded_rect(px, py, edge, edge, side, side, side * CORNER), TEAL, 1)
    alpha[:] = a
    # The 1024 artwork maps onto the tile.
    unit = side / 1024
    ax, ay = (px - edge) / unit, (py - edge) / unit
    for kind, c, g in ART:
        paint(distance(kind, g, ax, ay), c, 1 / unit)
    # Colours were blended against black outside the tile; undo that so the
    # rim is teal at partial alpha rather than dark.
    safe = np.where(alpha > 0, alpha, 1)[..., None]
    colour = np.where(alpha[..., None] > 0, colour / safe, 0)
    out = np.dstack([colour, alpha * 255])
    return np.clip(np.round(out), 0, 255).astype(np.uint8)


def png(rgba):
    h, w, _ = rgba.shape
    rows = b''.join(b'\0' + rgba[y].tobytes() for y in range(h))

    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body))

    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 9))
            + chunk(b'IEND', b''))


def ico(sizes):
    frames = [png(tile(s)) for s in sizes]
    head = struct.pack('<HHH', 0, 1, len(sizes))
    offset = 6 + 16 * len(sizes)
    for s, f in zip(sizes, frames):
        head += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(f), offset)
        offset += len(f)
    return head + b''.join(frames)


def rect_path(x, y, w, h, r):
    return (f'M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g} 0 0 1 {r:g},{r:g}'
            f'v{h - 2 * r:g}a{r:g},{r:g} 0 0 1 {-r:g},{r:g}'
            f'h{2 * r - w:g}a{r:g},{r:g} 0 0 1 {-r:g},{-r:g}'
            f'v{2 * r - h:g}a{r:g},{r:g} 0 0 1 {r:g},{-r:g}z')


def foreground():
    """Android's adaptive-icon foreground. The launcher shows the middle
    72dp of the 108dp layer, so the 1024 artwork maps onto that."""
    unit = 72 / 1024

    def at(v):
        return round(18 + v * unit, 3)

    paths = []
    for kind, c, g in ART:
        if kind == 'circle':
            cx, cy, r = at(g[0]), at(g[1]), round(g[2] * unit, 3)
            d = (f'M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1 0 {2 * r:g},0'
                 f'a{r:g},{r:g} 0 1 0 {-2 * r:g},0z')
        else:
            x, y, w, h, r = g
            d = rect_path(at(x), at(y), round(w * unit, 3), round(h * unit, 3),
                          round(r * unit, 3))
        paths.append(f'    <path\n        android:fillColor="{c}"\n'
                     f'        android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tool/make_app_icon.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            + '\n'.join(paths) + '\n</vector>\n')


def write(path, data):
    path = os.path.join(APP, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data if isinstance(data, bytes) else data.encode())


def main():
    windows = ico([16, 20, 24, 32, 40, 48, 64, 128, 256])
    write('windows/runner/resources/app_icon.ico', windows)
    write('../docs/assets/novel-icon.ico', windows)
    res = 'android/app/src/main/res'
    for folder, s in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96),
                      ('xxhdpi', 144), ('xxxhdpi', 192)]:
        write(f'{res}/mipmap-{folder}/ic_launcher.png', png(tile(s)))
    write(f'{res}/drawable/ic_launcher_foreground.xml', foreground())
    write(f'{res}/values/ic_launcher_background.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="ic_launcher_background">{TEAL}</color>\n</resources>\n')
    write(f'{res}/mipmap-anydpi-v26/ic_launcher.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n'
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@color/ic_launcher_background" />\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '</adaptive-icon>\n')
    print('icons written')


if __name__ == '__main__':
    main()
